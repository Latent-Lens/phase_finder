def check(canonical: Path) -> int:
    with tempfile.TemporaryDirectory(prefix="phasefinder-qc-cal-check-") as temp_name:
        generated = Path(temp_name) / "qc_calibration"
        _build_all(generated)
        expected_files = sorted(path.name for path in generated.iterdir())
        canonical_files = sorted(path.name for path in canonical.iterdir()) if canonical.is_dir() else []
        if expected_files != canonical_files:
            print("Generated file list differs from the committed fixtures.", file=sys.stderr)
            print("expected:", *expected_files, sep="\n  ", file=sys.stderr)
            print("committed:", *canonical_files, sep="\n  ", file=sys.stderr)
            return 1
        mismatches = [
            name for name in expected_files
            if (generated / name).read_bytes() != (canonical / name).read_bytes()
        ]
        if mismatches:
            print("Regeneration mismatch:", *mismatches, sep="\n  ", file=sys.stderr)
            return 1
    print(f"QC-calibration fixtures are reproducible ({len(expected_files)} files checked).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Regenerate in a temporary directory and byte-compare.")
    args = parser.parse_args()
    output = args.output.resolve()
    if args.check:
        return check(output)
    manifest_path = _build_all(output)
    fixture_count = len(json.loads(manifest_path.read_text(encoding="utf-8"))["fixtures"])
    print(f"Generated {fixture_count} QC-calibration fixtures at {output}")
    print(f"Manifest: {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
