            "conflated fractions. DOUBLET_HEAVY_FRACTION is deliberately set inside "
            "that still-reliable range so this fixture checks detection, not the "
            "breakdown point; the breakdown itself is a real, separate finding worth "
            "a scientific-result-contract note, not something this fixture asserts."
