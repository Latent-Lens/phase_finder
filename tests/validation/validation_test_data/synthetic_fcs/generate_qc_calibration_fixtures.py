import hashlib
import json
import random
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from fcs_factory import Parameter, write_fcs  # noqa: E402

GENERATOR_NAME = "phasefinder-qc-calibration-synthetic"
GENERATOR_VERSION = "1.0.0"
SCHEMA_VERSION = 1
DEFAULT_OUTPUT = HERE / "qc_calibration"

PARAMETER_NAMES = ("DNA-A", "DNA-H", "DNA-W", "FSC-A", "SSC-A", "Time")

# Pulse/scatter model constants. Arbitrary but internally consistent units;
# nothing here is calibrated to a real instrument.
AREA_SCALE = 20_000.0
HEIGHT_SCALE = 9_000.0
BASE_WIDTH = 40.0
FSC_MEAN = 50_000.0
SSC_MEAN = 30_000.0

BASELINE_DOUBLET_FRACTION = 0.04
BASELINE_DEBRIS_FRACTION = 0.03
DOUBLET_HEAVY_FRACTION = 0.08
DEBRIS_DOMINANT_FRACTION = 0.60

EVENT_COUNT = 6_000
EVENT_RATE_HZ = 50.0
STABLE_TIME_RANGE = 100_000.0
ROLLOVER_TIME_RANGE = 40.0

DNA_A_RANGE = 262_144
DNA_H_RANGE = 131_072
DNA_W_RANGE = 1_024
FSC_A_RANGE = 262_144
SSC_A_RANGE = 262_144

CLOG_WINDOW = (2_400, 3_000)  # [start, end) event indexes, acquisition order
CLOG_RATE_STRETCH = 15.0
CLOG_FSC_MULTIPLIER = 1.18
CLOG_SSC_MULTIPLIER = 1.12
CLOG_DNA_A_MULTIPLIER = 1.05

DROPOUT_INDEX = 3_300  # gap inserted immediately before this event index
DROPOUT_GAP_SECONDS = 25.0

JUMP_INDEX = 2_700  # backward-time-jump segment boundary
JUMP_RESTART_OFFSET = 2.0


def _stream_rng(seed: int, stream: str) -> random.Random:
    """A named, SHA-256-derived, independent RNG stream (same technique as
    generate_fixtures.py) so each aspect of a fixture (biology, pulse noise,
    scatter noise, timing) can be perturbed without cross-contaminating another
    aspect's sequence, and the whole corpus is bit-reproducible from its seed."""
    digest = hashlib.sha256(f"{GENERATOR_VERSION}:{seed}:{stream}".encode()).digest()
    return random.Random(int.from_bytes(digest[:8], "big"))


def _truncated_normal(rng: random.Random, mean: float, sd: float, minimum: float = 1e-6) -> float:
    while True:
        value = rng.gauss(mean, sd)
        if value > minimum:
            return value


def _relative_dna_content(rng: random.Random) -> float:
    """G1 (60%) / S-bridge (25%) / G2 (15%) relative DNA content; G1=1.0, G2=2.0."""
    roll = rng.random()
    if roll < 0.60:
        return _truncated_normal(rng, 1.0, 0.04)
    if roll < 0.85:
        return rng.uniform(1.0, 2.0)
    return _truncated_normal(rng, 2.0, 0.06)


def _singlet_pulse(rng: random.Random, content: float) -> tuple[float, float, float]:
    area = content * AREA_SCALE * (1 + rng.gauss(0.0, 0.02))
    height = content * HEIGHT_SCALE * (1 + rng.gauss(0.0, 0.025))
    # A mild width/content correlation, as seen on real instruments, rather
    # than a content-independent nuisance value -- see the doublet-heavy
    # calibration note in _build_doublet_heavy() for why this matters.
    width = BASE_WIDTH * (1 + 0.1 * (content - 1.0)) * (1 + rng.gauss(0.0, 0.03))
    return max(area, 0.0), max(height, 0.0), max(width, 1.0)


def _doublet_pulse(rng: random.Random, content_a: float, content_b: float) -> tuple[float, float, float]:
    """Two coincident cells: Area sums (the detector integrates total
    fluorescence over the extended pulse) but Height does not double -- the
    electronics peak-detect one dominant crest, not a sum -- and Width widens.
    This is the physically-motivated Area/Height/Width divergence that a
    doublet-discrimination ridge gate is built to catch."""
    area = (content_a + content_b) * AREA_SCALE * (1 + rng.gauss(0.0, 0.02))
    height = max(content_a, content_b) * HEIGHT_SCALE * 0.55 * (1 + rng.gauss(0.0, 0.025))
    width = BASE_WIDTH * 1.8 * (1 + rng.gauss(0.0, 0.04))
    return max(area, 0.0), max(height, 0.0), max(width, 1.0)


def _live_scatter(rng: random.Random) -> tuple[float, float]:
    size_factor = _truncated_normal(rng, 1.0, 0.12, minimum=0.3)
    fsc = FSC_MEAN * size_factor * (1 + rng.gauss(0.0, 0.05))
    ssc = SSC_MEAN * size_factor * (1 + rng.gauss(0.0, 0.08))
    return max(fsc, 1.0), max(ssc, 1.0)


def _debris_scatter(rng: random.Random) -> tuple[float, float]:
    size_factor = _truncated_normal(rng, 0.22, 0.08, minimum=0.03)
    fsc = FSC_MEAN * size_factor * (1 + rng.gauss(0.0, 0.15))
    ssc = SSC_MEAN * size_factor * 0.6 * (1 + rng.gauss(0.0, 0.2))
    return max(fsc, 1.0), max(ssc, 1.0)


def _debris_pulse(rng: random.Random) -> tuple[float, float, float]:
    """Debris is not real cell-cycle content: a small, noisy, roughly
    exponential DNA-A signal (autofluorescence/fragments), not a G1/S/G2
    mixture, with an irregular (high relative jitter) pulse width."""
    content = rng.expovariate(1 / 0.18)
    width = BASE_WIDTH * (1 + rng.gauss(0.0, 0.25))
    area = content * AREA_SCALE * (1 + rng.gauss(0.0, 0.1))
    height = area / max(width, 1e-6) * BASE_WIDTH * 0.6
    return max(area, 0.0), max(height, 0.0), max(width, 1.0)


def _generate_population(
    seed: int,
    event_count: int,
    *,
    doublet_fraction: float,
    debris_fraction: float,
) -> list[dict]:
    """Generates biological/pulse identity per event, in acquisition order.
    Time is assigned separately by the caller so a scenario's Time disturbance
    can be layered on independently of which events are doublets/debris."""
    rng_debris = _stream_rng(seed, "debris-membership")
    rng_doublet = _stream_rng(seed, "doublet-membership")
    rng_dna = _stream_rng(seed, "dna-content")
    rng_pulse = _stream_rng(seed, "pulse-noise")
    rng_scatter = _stream_rng(seed, "scatter-noise")
    rng_debris_shape = _stream_rng(seed, "debris-shape")

    events = []
    for _ in range(event_count):
        is_debris = rng_debris.random() < debris_fraction
        if is_debris:
            area, height, width = _debris_pulse(rng_debris_shape)
            fsc, ssc = _debris_scatter(rng_scatter)
            events.append({
                "area": area, "height": height, "width": width,
                "fsc": fsc, "ssc": ssc,
                "is_debris": True, "is_doublet": False,
            })
            continue

        is_doublet = rng_doublet.random() < doublet_fraction
        if is_doublet:
            content_a = _relative_dna_content(rng_dna)
            content_b = _relative_dna_content(rng_dna)
            area, height, width = _doublet_pulse(rng_pulse, content_a, content_b)
        else:
            content = _relative_dna_content(rng_dna)
            area, height, width = _singlet_pulse(rng_pulse, content)
        fsc, ssc = _live_scatter(rng_scatter)
        events.append({
            "area": area, "height": height, "width": width,
            "fsc": fsc, "ssc": ssc,
            "is_debris": False, "is_doublet": is_doublet,
        })
    return events


def _baseline_time(seed: int, event_count: int, rate_hz: float, stretch_windows: list[tuple[int, int, float]]) -> list[float]:
    """Cumulative event times from exponential inter-arrival gaps at a constant
    baseline rate, with optional index-range gap stretches layered in (for the
    clog fixture)."""
    rng_time = _stream_rng(seed, "inter-arrival")
    mean_gap = 1.0 / rate_hz
    time = 0.0
    times = []
    for index in range(event_count):
        gap = rng_time.expovariate(1.0 / mean_gap) if index > 0 else 0.0
        for start, end, factor in stretch_windows:
            if start <= index < end:
                gap *= factor
                break
        time += gap
        times.append(time)
    return times


def _apply_dropout(times: list[float], dropout_index: int, gap_seconds: float) -> list[float]:
    shifted = list(times)
    for index in range(dropout_index, len(shifted)):
        shifted[index] += gap_seconds
    return shifted


def _apply_rollover(times: list[float], timer_range: float) -> tuple[list[float], list[int]]:
    wrapped = []
    wrap_indices = []
    previous_cycle = None
    for index, value in enumerate(times):
        cycle = int(value // timer_range)
        if previous_cycle is not None and cycle != previous_cycle:
            wrap_indices.append(index)
        previous_cycle = cycle
        wrapped.append(value - cycle * timer_range)
    return wrapped, wrap_indices


def _apply_backward_jump(times: list[float], jump_index: int, restart_offset: float) -> list[float]:
    shifted = list(times)
    pivot = shifted[jump_index]
    for index in range(jump_index, len(shifted)):
        shifted[index] = (shifted[index] - pivot) + restart_offset
    return shifted


def _apply_clog_channel_distortion(events: list[dict], window: tuple[int, int]) -> None:
    start, end = window
    for index in range(start, end):
        events[index]["fsc"] *= CLOG_FSC_MULTIPLIER
        events[index]["ssc"] *= CLOG_SSC_MULTIPLIER
        events[index]["area"] *= CLOG_DNA_A_MULTIPLIER


def _parameters(time_range: float) -> list[Parameter]:
    return [
        Parameter("DNA-A", stain="DNA-A", bits=32, range=DNA_A_RANGE),
        Parameter("DNA-H", stain="DNA-H", bits=32, range=DNA_H_RANGE),
        Parameter("DNA-W", stain="DNA-W", bits=32, range=DNA_W_RANGE),
        Parameter("FSC-A", stain="FSC-A", bits=32, range=FSC_A_RANGE),
        Parameter("SSC-A", stain="SSC-A", bits=32, range=SSC_A_RANGE),
        Parameter("Time", stain="Time", bits=32, range=time_range, unit="s"),
    ]


def _rows(events: list[dict], times: list[float]) -> list[list[float]]:
    return [
        [event["area"], event["height"], event["width"], event["fsc"], event["ssc"], time]
        for event, time in zip(events, times)
    ]


def _write_fixture(output: Path, name: str, events: list[dict], times: list[float], time_range: float) -> dict:
    rows = _rows(events, times)
    parameters = _parameters(time_range)
    path = output / f"{name}.fcs"
    build = write_fcs(path, rows, parameters)
    return {
        "path": f"{name}.fcs",
        "sha256": build.sha256,
        "event_count": len(rows),
    }


def _index_list(events: list[dict], key: str) -> list[int]:
    return [index for index, event in enumerate(events) if event[key]]


def _build_stable(seed: int) -> tuple[list[dict], list[float], float, dict]:
    events = _generate_population(
        seed, EVENT_COUNT,
        doublet_fraction=BASELINE_DOUBLET_FRACTION,
        debris_fraction=BASELINE_DEBRIS_FRACTION,
    )
    times = _baseline_time(seed, EVENT_COUNT, EVENT_RATE_HZ, [])
    truth = {
        "category": "stable",
        "target_qc_module": None,
        "injected_disturbance": None,
        "doublet_fraction": BASELINE_DOUBLET_FRACTION,
        "debris_fraction": BASELINE_DEBRIS_FRACTION,
        "doublet_event_indices": _index_list(events, "is_doublet"),
        "debris_event_indices": _index_list(events, "is_debris"),
        "expected_behavior": (
            "Negative control / false-positive-rate baseline for all three gates. "
            "Time QC should report a single segment with no flagged intervals; the "
            "pulse-geometry and scatter gates should retain nearly all events at "
            "only the small background doublet/debris rate above."
        ),
    }
    return events, times, STABLE_TIME_RANGE, truth


def _build_clog(seed: int) -> tuple[list[dict], list[float], float, dict]:
    events = _generate_population(
        seed, EVENT_COUNT,
        doublet_fraction=BASELINE_DOUBLET_FRACTION,
        debris_fraction=BASELINE_DEBRIS_FRACTION,
    )
    _apply_clog_channel_distortion(events, CLOG_WINDOW)
    times = _baseline_time(seed, EVENT_COUNT, EVENT_RATE_HZ, [(*CLOG_WINDOW, CLOG_RATE_STRETCH)])
    truth = {
        "category": "clog",
        "target_qc_module": "js/analysis/qc/acquisition_time_qc.js (runTimeQC)",
        "injected_disturbance": {
            "type": "localized event-rate slowdown with mild scatter/DNA-A distortion",
            "affected_event_index_range": list(CLOG_WINDOW),
            "rate_stretch_factor": CLOG_RATE_STRETCH,
            "fsc_multiplier": CLOG_FSC_MULTIPLIER,
            "ssc_multiplier": CLOG_SSC_MULTIPLIER,
            "dna_a_multiplier": CLOG_DNA_A_MULTIPLIER,
        },
        "doublet_fraction": BASELINE_DOUBLET_FRACTION,
        "debris_fraction": BASELINE_DEBRIS_FRACTION,
        "doublet_event_indices": _index_list(events, "is_doublet"),
        "debris_event_indices": _index_list(events, "is_debris"),
        "expected_behavior": (
            "runTimeQC should flag the bin(s) overlapping event indexes "
            f"{list(CLOG_WINDOW)} via the eventRate metric (and plausibly "
            "medianFSC_A/medianSSC_A/medianDNA_A too), producing at least one "
            "flaggedInterval overlapping this range."
        ),
    }
    return events, times, STABLE_TIME_RANGE, truth


