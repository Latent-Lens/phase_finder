    truth = {
        "category": "dropout",
        "target_qc_module": "js/analysis/qc/acquisition_time_qc.js (runTimeQC)",
        "injected_disturbance": {
            "type": "full acquisition gap (no events observed for a span of time)",
            "gap_inserted_before_event_index": DROPOUT_INDEX,
            "gap_seconds": DROPOUT_GAP_SECONDS,
        },
        "doublet_fraction": BASELINE_DOUBLET_FRACTION,
        "debris_fraction": BASELINE_DEBRIS_FRACTION,
        "doublet_event_indices": _index_list(events, "is_doublet"),
        "debris_event_indices": _index_list(events, "is_debris"),
        "expected_behavior": (
            f"The bin(s) spanning event index {DROPOUT_INDEX} should show a sharply "
            "elongated duration (hence depressed eventRate) relative to the robust "
            "baseline and be flagged; no channel-value distortion is injected here, "
            "only a timing gap."
        ),
    }
    return events, times, STABLE_TIME_RANGE, truth


