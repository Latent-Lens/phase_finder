#!/usr/bin/env python3
"""Synthetic, labelled QC-calibration fixtures for QC-CAL-01.

These seven FCS files are NOT real instrument acquisitions. Every event,
timestamp, and disturbance below is synthetically generated by this script
with the injected ground truth recorded in the sidecar manifest
(``qc_calibration/manifest.json``) -- never inferred, never embedded in the
FCS parameters themselves. They exist so the Time QC (``acquisition_time_qc.js``),
pulse-geometry singlet gate (``pulse_geometry_gate.js``), and scatter GMM cell
gate (``scatter_gmm_gate.js``) detectors can be exercised against a *known*,
controlled disturbance instead of only biological or parser-conformance truth.

This calibrates detection *behavior* against a known injected truth. It does
NOT and cannot substitute for QC-CAL-01's actual ask: real, independently
labelled acquisitions from an instrument operator or orthogonal source. Do not
represent these fixtures as real acquisitions in any report or discussion.

Like ``generate_fixtures.py``, this generator is deliberately independent of
PhaseFinder's production detector code -- it knows nothing about robust
z-scores, MAD thresholds, or ridge fitting. It only knows the physical/pulse
model used to synthesize events and the disturbances it deliberately injects.

Usage:
    python3 generate_qc_calibration_fixtures.py            # write fixtures + manifest
    python3 generate_qc_calibration_fixtures.py --check    # verify reproducibility
"""

